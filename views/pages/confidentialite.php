    <h1>Politique de confidentialité</h1>
    <p>Vite &amp; Gourmand attache une grande importance à la protection de vos données personnelles, conformément au Règlement général sur
        la protection des données (RGPD) et à la loi Informatique et Libertés.</p>

    <h2 class="h4 mt-4">Responsable du traitement</h2>
    <p>Vite &amp; Gourmand, 12 cours de l'Intendance, 33000 Bordeaux — contact@vite-gourmand.fr.</p>

    <h2 class="h4 mt-4">Données collectées et finalités</h2>
    <ul>
        <li><strong>Compte client</strong> : nom, prénom, e-mail, GSM, adresse postale — gestion du compte et des commandes (exécution du contrat).</li>
        <li><strong>Commandes</strong> : adresse, date et heure de prestation, menu, montant — préparation, livraison et facturation.</li>
        <li><strong>Avis</strong> : note et commentaire, publiés avec votre prénom et l'initiale de votre nom uniquement.</li>
        <li><strong>Formulaire de contact</strong> : e-mail, titre et message — réponse à votre demande (intérêt légitime).</li>
        <li><strong>Sécurité</strong> : adresse IP des tentatives de connexion échouées, conservée 15 minutes à des fins de protection contre les attaques.</li>
    </ul>
    <p>Seules les données strictement nécessaires sont demandées (principe de minimisation). Vos mots de passe sont stockés sous forme
        hachée et ne sont jamais lisibles, y compris par notre équipe.</p>

    <h2 class="h4 mt-4">Durée de conservation</h2>
    <p>Les données du compte sont conservées tant que le compte est actif, puis supprimées après 3 ans d'inactivité. Les données de facturation
        sont conservées 10 ans (obligation comptable), sous forme anonymisée en cas de suppression du compte.</p>

    <h2 class="h4 mt-4">Destinataires</h2>
    <p>Vos données sont uniquement accessibles à l'équipe de Vite &amp; Gourmand et à nos sous-traitants techniques (hébergement, envoi d'e-mails),
        liés par un contrat de sous-traitance. Elles ne sont jamais vendues.</p>

    <h2 class="h4 mt-4">Vos droits</h2>
    <p>Vous disposez d'un droit d'accès, de rectification, d'effacement, de limitation, d'opposition et de portabilité. Vous pouvez modifier vos
        informations et <strong>supprimer votre compte</strong> directement depuis « Mon espace &gt; Mes informations », ou nous écrire à
        contact@vite-gourmand.fr. Vous pouvez également introduire une réclamation auprès de la CNIL (www.cnil.fr).</p>

    <h2 class="h4 mt-4">Cookies</h2>
    <p>Un unique cookie de session, strictement nécessaire (connexion, protection des formulaires), est déposé. Il expire à la fermeture du navigateur.</p>
